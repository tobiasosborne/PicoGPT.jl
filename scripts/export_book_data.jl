# Export what the Shakespeare model learned, as data for the book's figures.
#
#     julia --project -t auto scripts/export_book_data.jl
#
# Reads artifacts/shakespeare/checkpoints/ (written by train_shakespeare.jl) and writes
#   artifacts/shakespeare/loss.json        loss curves (train and validation) and the run's settings
#   artifacts/shakespeare/samples.json     samples at several checkpoints and temperatures
#   artifacts/shakespeare/attention.json   attention matrices for a fixed prompt, per block and head
#   artifacts/shakespeare/embedding.json   the embedding matrix E, its principal components, similarities
# Every array is {shape, data} in column-major order; numbers are rounded to 5 significant
# digits (attention: 4).

include("common.jl")

BLAS.set_num_threads(1)

const OUT = artifact("shakespeare")
const SIG = 5
const TEMPERATURES = [0.5, 0.8, 1.0, 1.5]
const SAMPLE_STEPS = [0, 100, 300, 1000, 3000]          # plus the final step
const SAMPLE_PROMPT = "\n"
const SAMPLE_LENGTH = 400
# The opening of the validation text (never trained on). The repeated phrase shows heads
# that look back to where the same characters came before.
const ATTENTION_PROMPT = "GREMIO:\nGood morrow, neighbour Baptista.\n\nBAPTISTA:\nGood morrow, neighbour Gremio.\n"

function history()
    lines = readlines(joinpath(CHECKPOINTS, "history.tsv"))
    header = Symbol.(split(lines[1], '\t'))
    rows = [parse.(Float64, split(l, '\t')) for l in lines[2:end]]
    NamedTuple{Tuple(header)}(Tuple([r[k] for r in rows] for k in eachindex(header)))
end

function export_loss(final, h)
    c = final.c
    best = argmin(h.val_loss)
    settings = isfile(joinpath(CHECKPOINTS, "settings.txt")) ? readline(joinpath(CHECKPOINTS, "settings.txt")) : ""
    writejson(joinpath(OUT, "loss.json"), (
        description = "Loss (mean surprise, nats per character) of the Tiny Shakespeare model during training. " *
                      "train_loss and val_loss are measured on fixed sets of 256 windows of the training and " *
                      "validation text (the last 10%, never trained on); batch_loss is the mean loss of the " *
                      "training batches since the previous row.",
        model = (V = c.V, D = c.D, H = c.H, L = c.L, T = c.T, F = c.F, param_count = nparams(c), precision = "Float32"),
        settings,
        uniform = log(c.V),
        step = Int.(h.step), tokens = Int.(h.tokens), seconds = h.seconds, lr = h.lr,
        batch_loss = h.batch_loss, train_loss = h.train_loss, val_loss = h.val_loss,
        best = (step = Int(h.step[best]), val_loss = h.val_loss[best], train_loss = h.train_loss[best]),
        final = (step = Int(h.step[end]), val_loss = h.val_loss[end], train_loss = h.train_loss[end]),
    ); sig = SIG)
end

function export_samples(final, steps)
    abc = final.abc
    jobs = [(s, τ) for s in steps for τ in TEMPERATURES]
    texts = fetch.([Threads.@spawn begin
                        ck = load_checkpoint(checkpoint_path(s))
                        rng = Xoshiro(1000s + round(Int, 100τ))
                        x = generate(ck.θ, ck.c, encode(SAMPLE_PROMPT, abc), SAMPLE_LENGTH; τ, rng)
                        decode(x, abc)
                    end for (s, τ) in jobs])
    for ((s, τ), t) in zip(jobs, texts)
        s == last(steps) && println("\n── step $s, τ = $τ ──", t)
    end
    writejson(joinpath(OUT, "samples.json"), (
        description = "Text generated by the model at several points of its training, at several temperatures " *
                      "τ (each character drawn from softmax(z/τ)). Every sample starts from the prompt.",
        prompt = SAMPLE_PROMPT, length = SAMPLE_LENGTH, temperatures = TEMPERATURES, steps = steps,
        samples = [(step = s, temperature = τ, text = t) for ((s, τ), t) in zip(jobs, texts)],
    ))
end

function export_attention(final)
    (; c, abc, θ) = final
    x = reshape(encode(ATTENTION_PROMPT, abc), :, 1)
    T = length(x)
    trace = []
    Z, _ = gpt(θ, x, c; trace)
    A = cat((r.A[:, :, :, 1] for r in trace[2:end-1])...; dims = 4)          # T×T×H×L
    probs = softmax(Z; dims = 1)
    writejson(joinpath(OUT, "attention.json"), (
        description = "Attention matrices of the trained model on a prompt from the validation text. " *
                      "A[i, j, h, l] is how much character i (the reader) takes from character j ≤ i " *
                      "(the source) in head h of block l; each row sums to 1. probs[:, i] is the model's " *
                      "distribution for the character after character i.",
        step = final.step, prompt = ATTENTION_PROMPT, chars = string.(collect(ATTENTION_PROMPT)),
        vocab = string.(abc), T, H = c.H, L = c.L,
        A = tensor(A), probs = tensor(probs),
    ); sig = 4)
end

# Principal components of the embedding columns (one point in ℝᴰ per character).
function pca(E, k = 3)
    Ec = E .- sum(E, dims = 2) ./ size(E, 2)
    F = svd(Ec)
    coords = Diagonal(F.S[1:k]) * F.Vt[1:k, :]                  # k×V
    for r in eachrow(coords)
        r .*= sign(r[argmax(abs.(r))])                          # an axis' sign is arbitrary: fix it
    end
    (coords = tensor(coords), explained = F.S[1:k] .^ 2 ./ sum(F.S .^ 2))
end

cosines(M) = (n = M ./ norm.(eachcol(M))'; n' * n)          # of the columns of M

function export_embedding(first, final)
    E(ck) = Float64.(carve(ck.θ, ck.c).E)
    Ef = E(final)
    R = Matrix(Float64.(carve(final.θ, final.c).Wout)')        # D×V: column a reads out character a
    writejson(joinpath(OUT, "embedding.json"), (
        description = "The embedding matrix E (column a is the vector of character a), its principal " *
                      "components (coordinates of each character on the top 3, and the fraction of " *
                      "variance each explains), and the cosine similarity of every pair of characters. " *
                      "The same for the initial E, for contrast. E starts as N(0, 1) noise and training " *
                      "moves it comparatively little, so its principal components are dominated by that " *
                      "noise. The readout vectors (the rows of Wout, which start near 0) are all learned: " *
                      "readout.pca shows the model's own geometry of the alphabet.",
        step = final.step, vocab = string.(final.abc),
        E = tensor(Ef), pca = pca(Ef), cosine = tensor(cosines(Ef)),
        initial = (step = first.step, E = tensor(E(first)), pca = pca(E(first))),
        readout = (W = tensor(R), pca = pca(R), cosine = tensor(cosines(R))),
    ); sig = SIG)
end

function main()
    h = history()
    saved = [parse(Int, m[1]) for m in match.(r"^step_(\d+)\.bin$", readdir(CHECKPOINTS)) if m !== nothing]
    last_step = maximum(saved)                               # the end of training, once it has ended
    final = load_checkpoint(checkpoint_path(last_step))
    steps = [filter(s -> isfile(checkpoint_path(s)), SAMPLE_STEPS); last_step] |> unique
    println("final step $last_step; samples from steps $steps")
    println("wrote ", export_loss(final, h))
    println("wrote ", export_attention(final))
    println("wrote ", export_embedding(load_checkpoint(checkpoint_path(0)), final))
    println("wrote ", export_samples(final, steps))
end

main()
